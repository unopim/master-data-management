<?php

namespace Webkul\MasterDataManagement\Services;

use DateTimeImmutable;
use Webkul\MasterDataManagement\Enums\CodeStrategy;
use Webkul\MasterDataManagement\FieldTypes\FieldTypeRegistry;
use Webkul\MasterDataManagement\Models\CodeListVersion;
use Webkul\MasterDataManagement\Models\EntityType;
use Webkul\MasterDataManagement\Models\Field;
use Webkul\MasterDataManagement\Models\Record;
use Webkul\MasterDataManagement\Repositories\CodeListVersionRepository;
use Webkul\MasterDataManagement\Repositories\CodeRepository;
use Webkul\MasterDataManagement\Repositories\FieldRepository;
use Webkul\MasterDataManagement\Repositories\RelationRepository;

/**
 * Builds the record form's controls from the entity type's active fields and turns the posted form back into writer input.
 *
 * Per-locale fields are edited in one locale at a time: `masterdata.default_locale`, the locale their `required` rule
 * applies to, unless an active locale is asked for.
 */
class RecordFormBuilder
{
    /**
     * The form control of each field type; types missing here have no control on the form yet.
     */
    protected const array CONTROLS = [
        'text'        => 'text',
        'email'       => 'text',
        'url'         => 'text',
        'integer'     => 'number',
        'decimal'     => 'number',
        'textarea'    => 'textarea',
        'boolean'     => 'switch',
        'date'        => 'date',
        'datetime'    => 'datetime',
        'select'      => 'select',
        'multiselect' => 'multiselect',
        'measurement' => 'measurement',
        'reference'   => 'reference',
    ];

    public function __construct(
        protected FieldRepository $fieldRepository,
        protected FieldTypeRegistry $fieldTypeRegistry,
        protected FieldRuleBuilder $fieldRuleBuilder,
        protected CodeListVersionRepository $codeListVersionRepository,
        protected CodeRepository $codeRepository,
        protected RelationRepository $relationRepository,
    ) {}

    /**
     * The value controls of the type grouped by field group, in field position order, per-locale fields in the locale.
     *
     * @return list<array{group: ?string, fields: list<array<string, mixed>>}>
     */
    public function groups(EntityType $type, ?Record $record = null, ?string $locale = null): array
    {
        $locale ??= $this->fieldRuleBuilder->defaultLocale();

        $groups = [];

        $fields = $this->fieldRepository->activeFor($type->id);

        $references = $record instanceof Record && $fields->contains('type', 'reference')
            ? ($this->relationRepository->visibleReferenceUuids([(int) $record->id])[(int) $record->id] ?? [])
            : [];

        foreach ($fields as $field) {
            $key = (string) $field->group;

            $groups[$key] ??= ['group' => $field->group ?: null, 'fields' => []];

            $groups[$key]['fields'][] = $this->control($type, $field, $record, $locale, $references);
        }

        return array_values($groups);
    }

    /**
     * How the code of a new record is set: generated by the system, or typed into the form.
     *
     * @return array{generated: bool, hint: ?string}
     */
    public function codeMode(EntityType $type): array
    {
        if ($type->code_strategy === CodeStrategy::Pattern) {
            return ['generated' => true, 'hint' => trans('masterdata::app.records.form.code-pattern', ['pattern' => $type->code_pattern])];
        }

        $identifiers = $this->fieldRuleBuilder->identifierFields($type);

        if ($identifiers->isNotEmpty()) {
            return ['generated' => true, 'hint' => trans('masterdata::app.records.form.code-identifiers', [
                'fields' => $identifiers->map(fn (Field $field): string => $this->fieldLabel($field))->implode(', '),
            ])];
        }

        return ['generated' => false, 'hint' => null];
    }

    /**
     * The locales per-locale values can be edited in: the active locales, the default locale first.
     *
     * @return list<array{code: string, name: string}>
     */
    public function editableLocales(): array
    {
        $default = $this->fieldRuleBuilder->defaultLocale();

        return core()->getAllActiveLocales()
            ->sortBy(fn ($locale): string => ($locale->code === $default ? '0' : '1').$locale->name)
            ->map(fn ($locale): array => ['code' => (string) $locale->code, 'name' => (string) $locale->name])
            ->values()
            ->all();
    }

    /**
     * The locale to edit per-locale values in: the requested one when it is active, else the default locale.
     */
    public function editLocale(?string $requested): string
    {
        $codes = array_column($this->editableLocales(), 'code');

        return in_array($requested, $codes, true) ? (string) $requested : $this->fieldRuleBuilder->defaultLocale();
    }

    /**
     * Whether any active field of the type holds a value per locale.
     */
    public function hasLocalizedFields(EntityType $type): bool
    {
        return $this->fieldRepository->activeFor($type->id)->contains('value_per_locale', true);
    }

    /**
     * The active field the record label is taken from, if the type names one.
     */
    public function labelField(EntityType $type): ?Field
    {
        if (! $type->label_field_code) {
            return null;
        }

        return $this->fieldRepository->activeFor($type->id)->firstWhere('code', $type->label_field_code);
    }

    /**
     * The stored values no active field shows, as display rows: values of archived fields or of a type without fields.
     *
     * @return list<array{locale: ?string, key: string, value: string}>
     */
    public function otherValues(EntityType $type, Record $record): array
    {
        $fields = $this->fieldRepository->activeFor($type->id);

        $common = $fields->reject(fn (Field $field): bool => $field->value_per_locale)->pluck('code')->all();

        $localized = $fields->filter(fn (Field $field): bool => $field->value_per_locale)->pluck('code')->all();

        $rows = [];

        foreach ($record->values['common'] ?? [] as $key => $value) {
            if (! in_array((string) $key, $common, true)) {
                $rows[] = ['locale' => null, 'key' => (string) $key, 'value' => $this->display($value)];
            }
        }

        foreach ($record->values['locale_specific'] ?? [] as $locale => $values) {
            foreach ((array) $values as $key => $value) {
                if (! in_array((string) $key, $localized, true)) {
                    $rows[] = ['locale' => (string) $locale, 'key' => (string) $key, 'value' => $this->display($value)];
                }
            }
        }

        return $rows;
    }

    /**
     * Turn the posted `values` into the writer's input shape.
     *
     * Multiselect and multiple reference values arrive as a JSON or comma list. A switch has no empty state, so an
     * empty boolean is false:
     * the form posts an unchecked switch through its hidden companion, which the shared field state can blank.
     *
     * @param  array<string, mixed>  $values
     * @return array<string, mixed>
     */
    public function normalizeValues(EntityType $type, array $values): array
    {
        $fields = $this->fieldRepository->activeFor($type->id)
            ->filter(fn (Field $field): bool => in_array($field->type, ['multiselect', 'boolean'], true) || ($field->type === 'reference' && $field->multiple))
            ->keyBy('code');

        if ($fields->isEmpty()) {
            return $values;
        }

        foreach ($values['common'] ?? [] as $code => $value) {
            $field = $fields->get($code);

            if ($field instanceof Field && ! $field->value_per_locale) {
                $values['common'][$code] = $this->formValue($field, $value);
            }
        }

        foreach ($values['locale_specific'] ?? [] as $locale => $localeValues) {
            foreach ((array) $localeValues as $code => $value) {
                $field = $fields->get($code);

                if ($field instanceof Field && $field->value_per_locale) {
                    $values['locale_specific'][$locale][$code] = $this->formValue($field, $value);
                }
            }
        }

        return $values;
    }

    /**
     * Render a stored value as text.
     */
    public function display(mixed $value): string
    {
        if (is_bool($value)) {
            return $value ? '1' : '0';
        }

        return is_scalar($value) || $value === null
            ? (string) $value
            : (string) json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    }

    /**
     * Describe one field's control: input name, label, current value and, for selects, the code options; a
     * reference control also gets its async options route and whether it takes several records.
     *
     * @param  array<string, list<string>>  $references
     * @return array<string, mixed>
     */
    protected function control(EntityType $type, Field $field, ?Record $record, string $editLocale, array $references = []): array
    {
        $locale = $field->value_per_locale ? $editLocale : null;

        $control = $this->fieldTypeRegistry->has($field->type) ? (self::CONTROLS[$field->type] ?? null) : null;

        $value = match (true) {
            $control === 'reference' => implode(',', $references[$field->code] ?? []) ?: null,
            $locale === null         => $record?->values['common'][$field->code] ?? null,
            default                  => $record?->values['locale_specific'][$locale][$field->code] ?? null,
        };

        return [
            'code'     => $field->code,
            'label'    => $this->fieldLabel($field),
            'help'     => $field->help,
            'locale'   => $locale,
            'name'     => $locale === null ? 'values[common]['.$field->code.']' : 'values[locale_specific]['.$locale.']['.$field->code.']',
            'control'  => $control,
            'required' => ($locale === null || $locale === $this->fieldRuleBuilder->defaultLocale()) && $this->fieldRuleBuilder->isRequired($type, $field),
            'value'    => $value,
            'display'  => $this->display($value),
            'options'  => in_array($control, ['select', 'multiselect'], true) ? $this->codeOptions($field) : [],
            'multiple' => $field->multiple,
            'route'    => $control === 'reference' ? route('admin.masterdata.records.options', $type->code) : null,
            'query'    => $control === 'reference' ? ['field' => $field->code] : [],
        ];
    }

    /**
     * One page of the codes of the field's code list version in effect today matching the term, or the options of
     * the given codes, in the async select shape.
     *
     * @param  list<string>  $codes
     * @return array{options: list<array{id: string, label: string}>, page: int, lastPage: int}
     */
    public function searchCodeOptions(Field $field, ?string $term, array $codes, int $page, int $perPage): array
    {
        $today = new DateTimeImmutable('today');

        $version = $field->code_list_id === null ? null : $this->codeListVersionRepository->effectiveOn($field->code_list_id, $today);

        return $version instanceof CodeListVersion
            ? $this->codeRepository->searchForVersion($version->id, $today, $term, $codes, $page, $perPage)
            : ['options' => [], 'page' => 1, 'lastPage' => 1];
    }

    /**
     * The codes of the field's code list version in effect today.
     *
     * @return list<array{id: string, label: string}>
     */
    protected function codeOptions(Field $field): array
    {
        if ($field->code_list_id === null) {
            return [];
        }

        $today = new DateTimeImmutable('today');

        $version = $this->codeListVersionRepository->effectiveOn($field->code_list_id, $today);

        return $version instanceof CodeListVersion ? $this->codeRepository->optionsForVersion($version->id, $today) : [];
    }

    /**
     * The field's translated label, else its code.
     */
    protected function fieldLabel(Field $field): string
    {
        $label = $field->label;

        return is_string($label) && $label !== '' ? $label : $field->code;
    }

    /**
     * A posted multiselect or multiple reference value as a list, or a posted boolean with empty read as false.
     */
    protected function formValue(Field $field, mixed $value): mixed
    {
        if ($field->type === 'boolean') {
            return $value ?? '0';
        }

        if (! is_string($value)) {
            return $value;
        }

        $decoded = json_decode($value, true);

        if (is_array($decoded)) {
            return array_values($decoded);
        }

        return array_values(array_filter(array_map(trim(...), explode(',', $value)), fn (string $code): bool => $code !== ''));
    }
}
